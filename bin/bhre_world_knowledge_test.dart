import '../lib/bhre/knowledge/bhre_knowledge_domain.dart';
import '../lib/bhre/knowledge/bhre_knowledge_record.dart';
import '../lib/bhre/knowledge/bhre_knowledge_source.dart';
import '../lib/bhre/knowledge/bhre_knowledge_memory.dart';

void main() {
  final memory = BhreKnowledgeMemory();

  final source = BhreKnowledgeSource(
    id: 'world-source-001',
    name: 'BHRE World Knowledge',
    type: BhreKnowledgeSourceType.bhreGenerated,
    confidence: 0.94,
    verified: true,
  );

  final record = BhreKnowledgeRecord(
    id: 'knowledge-001',
    topic: 'Gempa Indonesia',
    content:
        'Informasi gempa yang telah dikumpulkan dan dianalisis BHRE.',
    domain: BhreKnowledgeDomain.naturalDisaster,
    sources: [source],
    createdAt: DateTime.now(),
    observedAt: DateTime.now(),
    confidence: 0.94,
    verified: true,
    generatedBy: 'BHRE',
  );

  memory.store(record);

  final results = memory.search('gempa');

  if (results.isEmpty) {
    throw StateError(
      'BHRE Knowledge Memory gagal menyimpan knowledge.',
    );
  }

  final result = results.first;

  if (result.generatedBy != 'BHRE') {
    throw StateError(
      'BHRE belum dikenali sebagai knowledge source.',
    );
  }

  if (result.sources.first.type !=
      BhreKnowledgeSourceType.bhreGenerated) {
    throw StateError(
      'Source type BHRE tidak sesuai.',
    );
  }

  print('BHRE WORLD KNOWLEDGE TEST: PASS');
  print('Topic: ${result.topic}');
  print('Domain: ${result.domain.name}');
  print('Generated by: ${result.generatedBy}');
  print('Source: ${result.sources.first.name}');
  print('Confidence: ${result.confidence}');
  print('Verified: ${result.verified}');
}
