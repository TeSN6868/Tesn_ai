import 'dart:io';

import '../lib/bhre/knowledge/bhre_knowledge_domain.dart';
import '../lib/bhre/knowledge/bhre_knowledge_record.dart';
import '../lib/bhre/knowledge/bhre_knowledge_request.dart';
import '../lib/bhre/knowledge/bhre_knowledge_source.dart';
import '../lib/bhre/source/bhre_source_evidence.dart';
import '../lib/bhre/source/bhre_source_evaluation.dart';
import '../lib/bhre/source/bhre_source_evidence_aggregator.dart';
import '../lib/bhre/source/bhre_source_kind.dart';
import '../lib/bhre/source/bhre_source_plan.dart';

BhreSourceEvaluation evaluation({
  required String id,
  required String name,
  required BhreSourceKind kind,
  required String content,
  required double confidence,
  required bool verified,
  required bool fresh,
  required DateTime observedAt,
}) {
  final evidence = BhreSourceEvidence(
    sourceId: id,
    sourceName: name,
    sourceKind: kind,
    query: 'Gempa terbaru di Indonesia',
    content: content,
    observedAt: observedAt,
    usable: true,
  );

  return BhreSourceEvaluation(
    evidence: evidence,
    confidence: confidence,
    verified: verified,
    fresh: fresh,
    reason: 'Test evidence.',
  );
}

void main() {
  final now = DateTime(2026, 8, 26, 10, 0);

  final request = BhreKnowledgeRequest(
    query: 'Gempa terbaru di Indonesia',
    domain: BhreKnowledgeDomain.naturalDisaster,
    type: BhreKnowledgeRequestType.latest,
  );

  const plan = BhreSourcePlan(
    query: 'Gempa terbaru di Indonesia',
    preferredSources: [
      BhreSourceKind.government,
      BhreSourceKind.scientific,
      BhreSourceKind.news,
    ],
    minimumSources: 2,
    requiresVerification: true,
    requiresFreshData: true,
    priority: BhreSourcePriority.primary,
  );

  final evaluations = [
    evaluation(
      id: 'bmkg',
      name: 'BMKG',
      kind: BhreSourceKind.government,
      content: 'Data gempa dari BMKG.',
      confidence: 1.0,
      verified: true,
      fresh: true,
      observedAt: now,
    ),
    evaluation(
      id: 'scientific-earthquake',
      name: 'Scientific Earthquake Database',
      kind: BhreSourceKind.scientific,
      content: 'Data ilmiah gempa.',
      confidence: 0.85,
      verified: true,
      fresh: true,
      observedAt: now.subtract(const Duration(minutes: 5)),
    ),
  ];

  const aggregator = BhreSourceEvidenceAggregator();

  final record = aggregator.aggregate(
    request: request,
    plan: plan,
    evaluations: evaluations,
    now: now,
  );

  stdout.writeln('');
  stdout.writeln('RECORD ID: ${record.id}');
  stdout.writeln('TOPIC: ${record.topic}');
  stdout.writeln('DOMAIN: ${record.domain.name}');
  stdout.writeln('SOURCES: ${record.sources.length}');
  stdout.writeln('CONFIDENCE: ${record.confidence}');
  stdout.writeln('VERIFIED: ${record.verified}');
  stdout.writeln('GENERATED BY: ${record.generatedBy}');
  stdout.writeln('OBSERVED AT: ${record.observedAt}');

  for (final source in record.sources) {
    stdout.writeln(
      '- ${source.id}'
      ' | ${source.name}'
      ' | type=${source.type.name}'
      ' | confidence=${source.confidence}'
      ' | verified=${source.verified}',
    );
  }

  if (record.sources.length != 2) {
    throw StateError('Aggregator harus menghasilkan 2 source.');
  }

  if (record.confidence != 0.85) {
    throw StateError(
      'Confidence record harus mengikuti confidence terendah.',
    );
  }

  if (!record.verified) {
    throw StateError('Record seharusnya verified.');
  }

  if (record.generatedBy != 'BHRE_SOURCE_AGGREGATOR') {
    throw StateError('generatedBy aggregator salah.');
  }

  if (record.observedAt != now) {
    throw StateError('observedAt harus mengambil timestamp terbaru.');
  }

  final bmkg = record.sources.firstWhere(
    (source) => source.id == 'bmkg',
  );

  final scientific = record.sources.firstWhere(
    (source) => source.id == 'scientific-earthquake',
  );

  if (bmkg.type != BhreKnowledgeSourceType.government) {
    throw StateError('BMKG harus bertipe government.');
  }

  if (scientific.type != BhreKnowledgeSourceType.scientific) {
    throw StateError('Scientific source harus bertipe scientific.');
  }

  if (bmkg.confidence != 1.0 || !bmkg.verified) {
    throw StateError('Metadata BMKG tidak benar.');
  }

  if (scientific.confidence != 0.85 || !scientific.verified) {
    throw StateError('Metadata scientific source tidak benar.');
  }

  var rejected = false;

  try {
    aggregator.aggregate(
      request: request,
      plan: plan,
      evaluations: [
        evaluations.first,
      ],
      now: now,
    );
  } on BhreSourceAggregationException {
    rejected = true;
  }

  if (!rejected) {
    throw StateError(
      'Aggregator harus menolak evidence yang kurang dari minimumSources.',
    );
  }

  stdout.writeln('');
  stdout.writeln('BHRE SOURCE EVIDENCE AGGREGATOR TEST: PASS');
}
