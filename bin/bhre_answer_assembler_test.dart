import 'dart:io';

import '../lib/bhre/answer/bhre_answer_assembler.dart';
import '../lib/bhre/answer/bhre_answer.dart';
import '../lib/bhre/knowledge/bhre_knowledge_candidate.dart';
import '../lib/bhre/knowledge/bhre_knowledge_domain.dart';
import '../lib/bhre/knowledge/bhre_knowledge_record.dart';

void main() {
  final now = DateTime(2026, 8, 26, 10, 0);

  final record = BhreKnowledgeRecord(
    id: 'gempa-001',
    topic: 'Gempa terbaru di Indonesia',
    content: 'BMKG melaporkan aktivitas gempa terbaru.',
    domain: BhreKnowledgeDomain.naturalDisaster,
    createdAt: now,
    observedAt: now,
    confidence: 0.95,
    verified: true,
    generatedBy: 'BHRE_SOURCE_AGGREGATOR',
  );

  final candidate = BhreKnowledgeCandidate(
    record: record,
    score: 0.92,
    reasons: const [
      'exact_topic',
      'domain_match',
      'verified',
    ],
  );

  const assembler = BhreAnswerAssembler();

  final result = assembler.assemble(
    query: 'Gempa terbaru di Indonesia',
    candidates: [candidate],
    answer: 'Terdapat aktivitas gempa terbaru di Indonesia.',
    now: now,
  );

  if (result.query != 'Gempa terbaru di Indonesia') {
    throw StateError('Query answer tidak sesuai.');
  }

  if (result.answer.isEmpty) {
    throw StateError('Answer tidak boleh kosong.');
  }

  if (result.domain != BhreKnowledgeDomain.naturalDisaster) {
    throw StateError('Domain answer tidak sesuai.');
  }

  if (result.confidence != 0.92) {
    throw StateError('Confidence answer tidak sesuai.');
  }

  if (!result.verified) {
    throw StateError('Answer seharusnya verified.');
  }

  if (result.knowledge.length != 1) {
    throw StateError('Knowledge reference tidak sesuai.');
  }

  if (result.knowledge.first.id != 'gempa-001') {
    throw StateError('Knowledge reference salah.');
  }

  if (result.generatedBy != 'BHRE_ANSWER_ASSEMBLER') {
    throw StateError('Generator answer tidak sesuai.');
  }

  stdout.writeln('');
  stdout.writeln('QUERY: ${result.query}');
  stdout.writeln('ANSWER: ${result.answer}');
  stdout.writeln('DOMAIN: ${result.domain.name}');
  stdout.writeln('CONFIDENCE: ${result.confidence}');
  stdout.writeln('VERIFIED: ${result.verified}');
  stdout.writeln('KNOWLEDGE: ${result.knowledge.length}');
  stdout.writeln('GENERATED BY: ${result.generatedBy}');
  stdout.writeln('');
  stdout.writeln('BHRE ANSWER ASSEMBLER TEST: PASS');
}
